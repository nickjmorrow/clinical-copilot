def test_no_predicates_is_refused():
    """An unfiltered query is every patient in the hospital."""
    with pytest.raises(InvalidPredicateError, match="no predicates"):
        patient_query([], today=TODAY)


async def test_values_are_bound_not_interpolated(seeded):
    """The structural claim the definitions layer rests on.

    The compiled SQL must carry placeholders, not literals. If a threshold
    ever appears inline in the statement text, something is building SQL by
    concatenation and the injection argument for structured `logic` is void.
    """
    resolution = await definition_service.resolve_terms(seeded, terms=["impaired renal function"])
    query = patient_query([r.predicate for r in resolution.resolved], today=TODAY)
    compiled = str(query.compile())

    assert "60" not in compiled
    assert ":" in compiled
